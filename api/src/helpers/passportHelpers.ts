const nationalityLookupCache = new WeakMap<
  ExcelJs.Worksheet,
  Map<string, string>
>();

const getNationalityLookup = (sheet: ExcelJs.Worksheet) => {
  const cachedLookup = nationalityLookupCache.get(sheet);
  if (cachedLookup) return cachedLookup;

  const lookup = new Map<string, string>();

  sheet.eachRow((row, rowNumber) => {
    if (rowNumber === 1) return;

    const icao = String(row.getCell(2).value || "")
      .trim()
      .toUpperCase();
    if (!icao) return;

    [icao, row.getCell(3).value, row.getCell(4).value].forEach((value) => {
      const key = normalizeNationality(String(value || ""));
      if (key) lookup.set(key, icao);
    });
  });

  nationalityLookupCache.set(sheet, lookup);
  return lookup;
};

